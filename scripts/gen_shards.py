"""Generate fresh warmup shards from a trained checkpoint.

    python scripts/gen_shards.py --ckpt runs/x/best.pt --n 24 --out data/warmup_old

Writes `round_XXXXXX.npz` files in exactly the format the training loop produces
(`x` int16 [B, D], `log_rnd` float32 [B]), so they can be fed straight into
`--warmup-shards`.

Why bother when the run already saved shards: those come from whatever beta each
round was at, so only the last few are at the target temperature, and they were
generated by mid-training weights.  Regenerating from the *final* checkpoint
gives warmup data that is uniformly at the target beta and from a single policy.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

os.environ.setdefault("TQDM_DISABLE", "1")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import torch  # noqa: E402

from mdns import device as dev_mod  # noqa: E402
from mdns.losses import EMA, scan  # noqa: E402
from mdns.models.registry import build_from_config  # noqa: E402
from mdns.physics import potts2d_ham  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--n", type=int, default=24, help="number of shards")
    ap.add_argument("--batch", type=int, default=1024, help="samples per shard")
    ap.add_argument("--beta", type=float, default=None, help="override the reward beta")
    ap.add_argument("--out", required=True)
    ap.add_argument("--device", default="auto")
    args = ap.parse_args()

    dev = dev_mod.resolve(args.device)
    ck = torch.load(args.ckpt, map_location=dev, weights_only=False)
    ac = ck["arch"]
    L, q = ac["L"], ac["vocab_size"] - 1
    beta = args.beta if args.beta is not None else 1.2
    model = build_from_config(ac, L=L, vocab_size=ac["vocab_size"], device=dev)
    model.load_state_dict(ck["model"])
    ema = EMA(list(model.parameters()), decay=0.999)
    if "ema" in ck:
        ema.load_state_dict(ck["ema"])
    ema.copy_to(list(model.parameters()))     # sample from the EMA weights
    model.eval()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    reward = lambda x: -beta * potts2d_ham(x, 1.0, q)
    print(f"model: {ck.get('sakura_name', ac.get('name'))}  L={L} q={q} beta={beta}")
    print(f"writing {args.n} shards x {args.batch} samples -> {out}")
    for i in range(args.n):
        x, log_rnd = scan(model, reward, args.batch, dev)
        np.savez_compressed(out / f"round_{i:06d}.npz",
                            x=x.cpu().numpy().astype(np.int16),
                            log_rnd=log_rnd.cpu().numpy().astype(np.float32))
        if (i + 1) % 4 == 0 or i == args.n - 1:
            print(f"  {i + 1}/{args.n} shards", flush=True)
    print(f"done: {args.n * args.batch} samples")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
